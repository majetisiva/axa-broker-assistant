function lang(l) { return LANGS.includes(l) ? l : 'en'; }

// Returns the message for `key` in `l` (falls back to English). Arrays and objects are returned as is.
function t(l, key, vars = {}) {
  const s = M[lang(l)][key] ?? M.en[key];
  if (s === undefined) return key;
  if (typeof s === 'function') return s(vars);
  if (typeof s !== 'string') return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

function joinList(items, l, word = 'and') {
  if (items.length <= 1) return items.join('');
  return `${items.slice(0, -1).join(', ')} ${t(l, word)} ${items[items.length - 1]}`;
}

module.exports = { LANGS, t, joinList, lang };
